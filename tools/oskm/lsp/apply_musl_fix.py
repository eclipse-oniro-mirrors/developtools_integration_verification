"""Apply the clangd nullptr_t fix to the musl sysroot inside a build output dir.

libcxx-ohos's <cstddef> does `using ::nullptr_t`, but musl's stddef.h never
defines nullptr_t (only the compiler's builtin stddef.h does). Under clangd's
include-chain order musl's stddef.h always wins the search, so every C++ TU
degrades with a ~17-error cascade unless the typedef exists here too.

The patched file lives inside the build output (regenerated by every full
build), so this must run after compilation and before indexing.

Usage (standalone):
    python3 apply_musl_fix.py -i out/rk3568

Or import:  apply_musl_fix("/abs/path/to/out")
Returns a list of patched (or already-patched) stddef.h paths.

Use revert_musl_fix() to strip the shim again once indexing is done, so the
patched sysroot is left exactly as the build produced it.
"""

import argparse
import glob
import os

PATCH = """
/*
 * clangd shim: libcxx-ohos's <cstddef> does `using ::nullptr_t`, but musl
 * never defines it (only the compiler's builtin stddef.h does). Patched in
 * the out/ sysroot so clangd parses OHOS C++ TUs correctly.
 * NOTE: regenerated by every musl rebuild; re-run apply_musl_fix.py after.
 */
#if defined(__cplusplus) && __cplusplus >= 201103L
typedef decltype(nullptr) nullptr_t;
#endif
"""


def apply_musl_fix(out_dir):
    out_dir = os.path.abspath(out_dir)
    results = []
    pattern = os.path.join(out_dir, "obj", "third_party", "musl",
                           "usr", "include", "*", "stddef.h")
    for stddef in sorted(glob.glob(pattern)):
        try:
            with open(stddef, "r", encoding="utf-8") as f:
                content = f.read()
        except OSError:
            continue
        if "clangd shim" in content:
            results.append((stddef, "already-patched"))
            continue
        marker = "#define _STDDEF_H\n"
        if marker not in content:
            results.append((stddef, "UNEXPECTED-LAYOUT-SKIPPED"))
            continue
        content = content.replace(marker, marker + PATCH, 1)
        with open(stddef, "w", encoding="utf-8") as f:
            f.write(content)
        results.append((stddef, "patched"))
    return results


def revert_musl_fix(out_dir):
    """Strip the clangd shim from the musl sysroot inside a build output dir.

    Exact inverse of apply_musl_fix(): removes the previously inserted PATCH
    block (identified by the "clangd shim" marker) and restores the original
    file byte-for-byte. Files without the marker are left untouched, so this
    is idempotent and safe to call even when nothing was ever patched.

    Returns a list of (stddef_path, status) tuples.
    """
    out_dir = os.path.abspath(out_dir)
    results = []
    pattern = os.path.join(out_dir, "obj", "third_party", "musl",
                           "usr", "include", "*", "stddef.h")
    for stddef in sorted(glob.glob(pattern)):
        try:
            with open(stddef, "r", encoding="utf-8") as f:
                content = f.read()
        except OSError:
            continue
        if PATCH not in content:
            results.append((stddef, "not-patched"))
            continue
        content = content.replace(PATCH, "", 1)
        with open(stddef, "w", encoding="utf-8") as f:
            f.write(content)
        results.append((stddef, "reverted"))
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-i", "--input", required=True,
                        help="build output directory, e.g. out/rk3568")
    args = parser.parse_args()
    results = apply_musl_fix(args.input)
    if not results:
        print("[apply_musl_fix] no musl stddef.h found under {}".format(
            args.input))
        return 1
    for path, status in results:
        print("[apply_musl_fix] {}: {}".format(status, path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
