/** 取一个问题码的解释；未登记时按词尾兜底，再不行给通用提示。 */
export function explain(code) {
  if (ISSUES[code]) return { ...ISSUES[code], exact: true }
  for (const [re, title, what, why, fix] of FAMILIES) {
    if (re.test(code)) return { title, what, why, fix, exact: false }
  }
  return { ...UNKNOWN, exact: false }
}

